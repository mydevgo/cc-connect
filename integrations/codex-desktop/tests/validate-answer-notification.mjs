import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import {deliver} from '../notify.mjs';
const root=fs.mkdtempSync(path.join(os.tmpdir(),'answer-notification-'));
const transcript=path.join(root,'session.jsonl');
const id='desktop-session-notify';
fs.writeFileSync(transcript,JSON.stringify({type:'session_meta',payload:{id,source:'vscode',originator:'Codex Desktop'}})+'\n');
let message;
const options={codexHome:root,stateDir:path.join(root,'state'),answerDir:path.join(root,'questions'),sender:body=>{message=body;return {status:0}}};
const event={hook_event_name:'PreToolUse',tool_name:'functions.request_user_input_async',session_id:id,turn_id:'turn-1',tool_use_id:'call-1',transcript_path:transcript,tool_input:{questions:[{title:'测试选项',options:['一','二']}]}};
assert.equal(deliver(event,options).status,'sent');
assert.match(message,/飞书回复：\/answer Q-[A-F0-9]{12} 你的答案/);
assert.equal(fs.readdirSync(options.answerDir).length,1);
assert.equal(deliver(event,options).status,'duplicate');
assert.equal(fs.readdirSync(options.answerDir).length,1);
assert.match(message,/一；二/);
fs.rmSync(root,{recursive:true});
console.log('PASS: real notification delivery registers a durable question ID, emits /answer instructions, and deduplicates.');
