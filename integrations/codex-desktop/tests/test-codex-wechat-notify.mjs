import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { classify, toolFailure, deliver, isDesktopMain } from '../notify.mjs';

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'codex-wechat-test-'));
const transcript = path.join(root, 'desktop.jsonl');
const meta = { id: 'desktop-test-123', originator: 'Codex Desktop', source: 'vscode', cwd: 'E:\\cc-connect-workspace' };
fs.writeFileSync(transcript, JSON.stringify({ type: 'session_meta', payload: meta }) + '\n');
const event = { session_id: meta.id, turn_id: 'turn-1', transcript_path: transcript, cwd: meta.cwd, hook_event_name: 'Stop', last_assistant_message: '中文测试完成。' };
let messages = [];
const options = { codexHome: root, stateDir: path.join(root, 'state'), sender: body => { messages.push(body); return { status: 0 }; } };

assert.equal(deliver(event, options).status, 'sent');
assert.match(messages[0], /中文测试完成/);
assert.equal(deliver(event, options).status, 'duplicate');
assert.equal(messages.length, 1);
assert.equal(deliver({ ...event, turn_id: 'turn-2' }, options).status, 'sent');
assert.equal(deliver({ ...event, session_id: 'wrong-id' }, options).status, 'session-mismatch');
assert.equal(isDesktopMain({ ...meta, originator: 'codex_cli_rs', source: 'cli' }), false);
assert.equal(isDesktopMain({ ...meta, source: { subagent: { spawn: {} } } }), false);
assert.match(classify({ hook_event_name: 'PreToolUse', tool_name: 'request_user_input_async', tool_input: { questions: [{ title: '请选择', options: ['一', '二'] }] } }).body, /一；二/);
assert.equal(classify({ hook_event_name: 'PreToolUse', tool_name: 'Bash' }), null);
assert.equal(classify({ hook_event_name: 'PostModelRequest', status: 'completed' }), null);
assert.equal(classify({ hook_event_name: 'PostModelRequest', status: 'failed', error: 'timeout' }).category, 'model-error');
assert.equal(classify({ hook_event_name: 'PermissionRequest', tool_name: 'Bash', tool_input: { command: 'read' } }).category, 'permission');
assert.equal(toolFailure({ exit_code: 0, output: 'No error, 0 failures' }), null);
assert.ok(toolFailure({ exit_code: 3, output: 'failed' }));
assert.ok(toolFailure({ content: [{ type: 'text', text: 'Process exited with code 2\nfailed' }] }));
assert.ok(toolFailure({ isError: true, content: [] }));
assert.equal(toolFailure({ output: '{"error":false}' }), null);
assert.equal(classify({ hook_event_name: 'Stop', last_assistant_message: '' }), null);
assert.equal(classify({hook_event_name:'PostToolUse',tool_name:'Bash',tool_response:'failed command',tool_response_exit_code:23}).category,'tool-error');
assert.equal(classify({hook_event_name:'PostToolUse',tool_name:'Bash',tool_response:'successful command',tool_response_exit_code:0}),null);
const retryEvent = { ...event, turn_id: 'retry' };
assert.throws(() => deliver(retryEvent, { ...options, sender: () => ({ status: 1, stderr: 'test failure' }) }), /send failed/);
assert.equal(deliver(retryEvent, options).status, 'sent');
fs.writeFileSync(transcript, JSON.stringify({ type: 'session_meta', payload: { ...meta, source: 'cli', originator: 'codex_cli_rs' } }) + '\n');
assert.equal(deliver({ ...event, turn_id: 'cli' }, options).status, 'filtered-source');
console.log('PASS: Unicode, deduplication, turn isolation, desktop/CLI/subagent filtering, questions, permissions, model errors, tool errors, false-positive filtering, failed-send retry.');
